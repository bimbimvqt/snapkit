import { test, before, after } from 'node:test';
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
let child, state;
const port = 14319;
const base = `http://127.0.0.1:${port}`;
before(async () => {
  child = spawn(process.execPath, ['server/index.js', '--demo'], { env: { ...process.env, PORT: String(port) }, stdio: 'pipe' });
  await new Promise((resolve, reject) => { child.once('error', reject); child.stdout.on('data', b => { if (b.toString().includes('http://')) resolve(); }); child.once('exit', code => reject(new Error(`Server exited ${code}`))); });
  state = await fetch(`${base}/api/state`).then(r => r.json());
});
after(() => child?.kill());
const post = (route, body, token = state.token) => fetch(`${base}${route}`, { method: 'POST', headers: { 'Content-Type': 'application/json', 'X-Snapkit-Token': token }, body: JSON.stringify(body) });
test('API rejects missing mutation token and hostile origins', async () => {
  assert.equal((await post('/api/scan', {}, 'bad-token')).status, 403);
  assert.equal((await fetch(`${base}/api/state`, { headers: { Origin: 'https://untrusted.example' } })).status, 403);
});
test('device manager boots devices and selects one or more IDE targets without any app-run API', async () => {
  assert.equal((await post('/api/targets', { ids: ['demo-ios-2'] })).status, 400);
  assert.equal((await post('/api/devices/demo-ios-2/boot', {})).status, 200);
  let result = await post('/api/targets', { ids: ['demo-ios-1', 'demo-ios-2'] }).then(r => r.json());
  assert.deepEqual(result.settings.targetIds, ['demo-ios-1', 'demo-ios-2']);
  result = await post('/api/targets', { ids: ['demo-ios-1'] }).then(r => r.json());
  assert.deepEqual(result.settings.targetIds, ['demo-ios-1']);
  assert.equal((await post('/api/targets', { ids: ['demo-ios-1', 'demo-ios-1'] })).status, 400);
  assert.equal((await post('/api/targets', { ids: [] })).status, 200);
  for (const route of ['/api/sessions', '/api/sessions/reload-all', '/api/sessions/demo-ios-1/devtools', '/api/devices/demo-ios-1/shutdown', '/api/devices/demo-ios-1/screenshot', '/api/target']) assert.equal((await post(route, {})).status, 404);
  const current = await fetch(base + '/api/state').then(r => r.json());
  assert.equal('sessions' in current, false); assert.equal('logs' in current, false);
});
test('folder picker and provisioning APIs support demo creation and reject incompatible legacy model', async () => {
  const picked = await post('/api/folders/pick', {}).then(r => r.json());
  assert.match(picked.path, /SanDiskSSDData/);
  const catalog = await fetch(`${base}/api/provision/catalog`).then(r => r.json());
  assert.ok(catalog.ios.models.some(m => m.id === 'legacy:iphone-5' && m.runtimeIds.length === 0));
  const invalid = await post('/api/provision/create', { platform: 'ios', name: 'iPhone 5', model: 'legacy:iphone-5', runtime: 'demo:ios18' });
  assert.equal(invalid.status, 400);
  const created = await post('/api/provision/create', { platform: 'ios', name: 'Test iPhone', model: 'demo:iphone16', runtime: 'demo:ios18' }).then(r => r.json());
  assert.equal(created.job.status, 'completed');
  const current = await fetch(`${base}/api/state`).then(r => r.json());
  assert.ok(current.devices.some(d => d.name === 'Test iPhone'));
});
test('website API requires pairing for reads and commands, hides local token, and supports revocation', async () => {
  const origin = 'https://bimbimvqt.github.io';
  const request = (route, options = {}) => fetch(base + route, { ...options, headers: { Origin: origin, ...options.headers } });
  assert.equal((await request('/api/state')).status, 401);
  assert.equal((await request('/api/screenshots/test.png')).status, 401);
  const preflight = await request('/api/state', { method: 'OPTIONS', headers: { 'Access-Control-Request-Method': 'GET', 'Access-Control-Request-Headers': 'Authorization', 'Access-Control-Request-Private-Network': 'true' } });
  assert.equal(preflight.status, 204); assert.equal(preflight.headers.get('Access-Control-Allow-Origin'), origin);
  assert.equal(preflight.headers.get('Access-Control-Allow-Private-Network'), 'true');
  const pair = await post('/api/pairing/code', {}).then(r => r.json());
  const claimed = await request('/api/pairing/claim', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ code: pair.code }) }).then(r => r.json());
  const headers = { Authorization: `Bearer ${claimed.token}` };
  const remote = await request('/api/state', { headers }).then(r => r.json());
  assert.equal(Object.hasOwn(remote, 'token'), false); assert.ok(remote.devices.length);
  assert.equal((await request('/api/scan', { method: 'POST', headers })).status, 200);
  assert.equal((await request('/api/pairing/code', { method: 'POST', headers })).status, 403);
  assert.equal((await fetch(base + '/api/state', { headers: { ...headers, Origin: 'https://other.example' } })).status, 403);
  await post('/api/pairing/revoke', {});
  assert.equal((await request('/api/state', { headers })).status, 401);
});
