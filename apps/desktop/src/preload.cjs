const { contextBridge, ipcRenderer, webUtils } = require('electron');
contextBridge.exposeInMainWorld('snapkitDesktop', Object.freeze({
  focusExperience:legacy=>ipcRenderer.invoke('snapkit:focus-experience',legacy),
  focusAction:value=>ipcRenderer.invoke('snapkit:focus-action',value),
  onFocusExperience:callback=>{const handler=(_event,value)=>callback(value);ipcRenderer.on('snapkit:focus-experience',handler);return()=>ipcRenderer.removeListener('snapkit:focus-experience',handler);},
  miniOpen:()=>ipcRenderer.invoke('snapkit:mini-open'),
  miniFocus:value=>ipcRenderer.invoke('snapkit:mini-focus',value),
  miniTask:value=>ipcRenderer.invoke('snapkit:mini-task',value),
  onMiniFocus:callback=>{const handler=(_event,value)=>callback(value);ipcRenderer.on('snapkit:mini-focus',handler);return()=>ipcRenderer.removeListener('snapkit:mini-focus',handler);},
  onMiniNavigate:callback=>{const handler=(_event,target)=>callback(target||{});ipcRenderer.on('snapkit:mini-navigate',handler);return()=>ipcRenderer.removeListener('snapkit:mini-navigate',handler);},
  clipboardState:()=>ipcRenderer.invoke('snapkit:clipboard-state'),
  clipboardEnabled:value=>ipcRenderer.invoke('snapkit:clipboard-enabled',value),
  clipboardClear:()=>ipcRenderer.invoke('snapkit:clipboard-clear'),
  clipboardCopy:id=>ipcRenderer.invoke('snapkit:clipboard-copy',id),
  filePick:()=>ipcRenderer.invoke('snapkit:file-pick'),
  fileApply:(id,options)=>ipcRenderer.invoke('snapkit:file-apply',id,options),
  fileUndo:id=>ipcRenderer.invoke('snapkit:file-undo',id),
  captureSettings:()=>ipcRenderer.invoke('snapkit:capture-settings'),
  captureScreens:()=>ipcRenderer.invoke('snapkit:capture-screens'),
  kitSettings: () => ipcRenderer.invoke('snapkit:kit-settings'),
  kitStartup: enabled => ipcRenderer.invoke('snapkit:kit-startup', enabled),
  kitAwake: enabled => ipcRenderer.invoke('snapkit:kit-awake', enabled),
  kitPickFiles: () => ipcRenderer.invoke('snapkit:kit-pick'),
  kitDropFiles: files => ipcRenderer.invoke('snapkit:kit-drop', Array.from(files).map(file => webUtils.getPathForFile(file))),
  kitReveal: id => ipcRenderer.invoke('snapkit:kit-reveal', id),
  kitFolder: name => ipcRenderer.invoke('snapkit:kit-folder', name),
  kitFocus: deadline => ipcRenderer.invoke('snapkit:kit-focus', deadline),
  kitNotify: () => ipcRenderer.invoke('snapkit:kit-notify'),
  onKitCommand: callback => { const handler = () => callback(); ipcRenderer.on('snapkit:kit-command', handler); return () => ipcRenderer.removeListener('snapkit:kit-command', handler); },
  notifyTeam: data => ipcRenderer.invoke('snapkit:team-notify', data),
  onTeamNotification: callback => { const handler = (_event,target) => callback(target); ipcRenderer.on('snapkit:team-notification',handler); return () => ipcRenderer.removeListener('snapkit:team-notification',handler); },
  openXcode: () => ipcRenderer.invoke('snapkit:open-xcode'),
  chooseReleaseFile: kind => ipcRenderer.invoke('snapkit:release-file', kind),
  ready: () => ipcRenderer.send('snapkit:ready'),
  setLanguage: language => ipcRenderer.invoke('snapkit:language', language),
  version: () => ipcRenderer.invoke('snapkit:version'),
  checkUpdates: () => ipcRenderer.invoke('snapkit:updates'),
  updateState: () => ipcRenderer.invoke('snapkit:update-state'),
  downloadUpdate: () => ipcRenderer.invoke('snapkit:update-download'),
  cancelUpdate: () => ipcRenderer.invoke('snapkit:update-cancel'),
  installUpdate: () => ipcRenderer.invoke('snapkit:update-install'),
  setAppearance: value => ipcRenderer.invoke('snapkit:appearance', value),
  clearCache: () => ipcRenderer.invoke('snapkit:clear-cache'),
  openExternal: url => ipcRenderer.invoke('snapkit:external', url),
  restart: () => ipcRenderer.invoke('snapkit:restart')
}));
