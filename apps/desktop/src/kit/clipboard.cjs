'use strict';
const {randomUUID}=require('node:crypto');
const paused='Clipboard capture paused. Turn it on to try again.';
const privateFormat=/concealed|password|transient|excludeclipboard|excludefromclipboard|canincludeinclipboardhistory|canuploadtocloudclipboard/i;
const excluded=['org.nspasteboard.ConcealedType','org.nspasteboard.TransientType','org.nspasteboard.AutoGeneratedType','org.nspasteboard.ExcludeFromClipboardHistory','com.agilebits.onepassword','ExcludeClipboardContentFromMonitorProcessing','CanIncludeInClipboardHistory','CanUploadToCloudClipboard'];
function createClipboardHistory(clipboard){
 let enabled=false,items=[],last='',timer=null,epoch=0,collecting=false,error='';
 const state=()=>({enabled,items:items.map(item=>({...item})),...(error?{error}:{})});
 const stop=()=>{if(timer)clearInterval(timer);timer=null;};
 const fail=()=>{enabled=false;epoch++;stop();error=paused;};
 const start=()=>{timer=setInterval(()=>{void collect();},1000);};
 async function collect(){if(!enabled||collecting)return;collecting=true;const version=epoch;try{
  // Electron 45 exposes asynchronous read()/has() instead of availableFormats().
  if(!await clipboard.has('text/plain'))return;
  for(const format of excluded)if(await clipboard.has(`electron application/osclipboard;format="${format}"`))return;
  const entries=await clipboard.read();if(entries.some(item=>item.types.some(format=>privateFormat.test(format))))return;
  const entry=entries.find(item=>item.types.includes('text/plain'));if(!entry)return;
  const blob=await entry.getType('text/plain');if(blob.size>40000)return;const text=await blob.text();
  if(!enabled||version!==epoch||!text||text.length>10000||text===last)return;
  last=text;items=[{id:randomUUID(),text,at:Date.now()},...items.filter(item=>item.text!==text)].slice(0,40);
 }catch{if(version===epoch)fail();}finally{collecting=false;}}
 async function baseline(resume){const version=++epoch;enabled=false;stop();error='';try{const text=await clipboard.readText();if(version!==epoch)return state();last=text;enabled=resume;if(enabled)start();}catch{if(version===epoch)fail();}return state();}
 async function setEnabled(value){if(typeof value!=='boolean')throw Error('Invalid setting');if(!value){epoch++;enabled=false;error='';stop();return state();}return baseline(true);}
 async function clear(){items=[];return baseline(enabled);}
 async function copy(id){const item=items.find(item=>item.id===id);if(!item)throw Error('Clipboard item is no longer available');epoch++;await clipboard.writeText(item.text);last=item.text;return true;}
 function dispose(){epoch++;enabled=false;stop();items=[];last='';error='';}
 return {state,setEnabled,clear,copy,collect,dispose};
}
module.exports={createClipboardHistory};
